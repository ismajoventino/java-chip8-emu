package com.ismael.chip8.rom;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;

import com.ismael.chip8.core.Memory;

public class RomLoader {

	private static final int[] FONT_SET = {
            0xF0, 0x90, 0x90, 0x90, 0xF0,
            0x20, 0x60, 0x20, 0x20, 0x70,
            0xF0, 0x10, 0xF0, 0x80, 0xF0,
            0xF0, 0x10, 0xF0, 0x10, 0xF0,
            0x90, 0x90, 0xF0, 0x10, 0x10,
            0xF0, 0x80, 0xF0, 0x10, 0xF0,
            0xF0, 0x80, 0xF0, 0x90, 0xF0,
            0xF0, 0x10, 0x20, 0x40, 0x40,
            0xF0, 0x90, 0xF0, 0x90, 0xF0,
            0xF0, 0x90, 0xF0, 0x10, 0xF0,
            0xF0, 0x90, 0xF0, 0x90, 0x90,
            0xE0, 0x90, 0xE0, 0x90, 0xE0,
            0xF0, 0x80, 0x80, 0x80, 0xF0,
            0xE0, 0x90, 0x90, 0x90, 0xE0,
            0xF0, 0x80, 0xF0, 0x80, 0xF0,
            0xF0, 0x80, 0xF0, 0x80, 0x80
    };
	
	public void loadFonts(Memory memory) {
		for(int i = 0; i < FONT_SET.length; i++) {
			memory.write((0x050 + i), FONT_SET[i]);
		}
	}
	
	public void loadRom(String filePath, Memory memory) throws IOException {
		Path path = Paths.get(filePath);
		byte[] romBytes = Files.readAllBytes(path);
		
		for(int i = 0; i < romBytes.length; i++) {
			memory.write((0x200 + i), romBytes[i]);
		}
	}
	
	
}
